pub fn is_wall(x: i32, y: i32) -> bool {
    if x < 0 || y < 0 || x as usize >= MAP_W || y as usize >= MAP_H {
        return true;
    }
    let cell = GRID[y as usize][x as usize];
    cell >= 1 && cell <= 5
}

pub fn cell(x: i32, y: i32) -> u8 {
    if x < 0 || y < 0 || x as usize >= MAP_W || y as usize >= MAP_H {
        return 1;
    }
    GRID[y as usize][x as usize]
}

pub fn is_exit(x: i32, y: i32) -> bool {
    cell(x, y) == 9
}

